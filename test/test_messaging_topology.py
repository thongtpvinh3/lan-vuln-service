"""No database/NVD required: configuration and passive broker ownership checks."""
import importlib
import pika
import pytest

from app.common.config import RabbitMQConfig


@pytest.fixture
def client_env(monkeypatch):
    import os
    for key in os.environ:
        if key.startswith("RABBITMQ_"):
            monkeypatch.delenv(key)
    monkeypatch.setenv("RABBITMQ_URL", "amqp://unused")
    monkeypatch.setenv("RABBITMQ_TOPOLOGY_VERSION", "1")
    monkeypatch.setenv("RABBITMQ_EXCHANGE", "from-platform")
    monkeypatch.setenv("RABBITMQ_QUEUE", "from-platform.inbox")
    return monkeypatch


def test_generated_environment_is_required_and_no_topology_names_are_defaulted(client_env):
    cfg = RabbitMQConfig.from_env()
    assert (cfg.exchange, cfg.queue, cfg.topology_version) == ("from-platform", "from-platform.inbox", 1)
    client_env.delenv("RABBITMQ_QUEUE")
    with pytest.raises(ValueError, match="Platform-generated"):
        RabbitMQConfig.from_env()


@pytest.mark.parametrize("absolute", [False, True])
def test_generated_file_is_loaded_and_conflicting_override_is_rejected(client_env, tmp_path, monkeypatch, absolute):
    path = tmp_path / "assessment.env"
    path.write_text("# Generated by Platform\nRABBITMQ_TOPOLOGY_VERSION=1\n"
                    "RABBITMQ_EXCHANGE=custom\nRABBITMQ_QUEUE=custom.inbox\n")
    monkeypatch.setattr("app.common.config.PROJECT_ROOT", tmp_path)
    client_env.setenv("RABBITMQ_CLIENT_ENV_FILE", str(path) if absolute else path.name)
    client_env.delenv("RABBITMQ_EXCHANGE")
    client_env.delenv("RABBITMQ_QUEUE")
    assert RabbitMQConfig.from_env().queue == "custom.inbox"
    client_env.setenv("RABBITMQ_QUEUE", "conflict")
    with pytest.raises(ValueError, match="conflicts"):
        RabbitMQConfig.from_env()


def test_generated_file_cannot_inject_credentials(client_env, tmp_path):
    path = tmp_path / "assessment.env"
    path.write_text("RABBITMQ_URL=amqp://secret\n")
    client_env.setenv("RABBITMQ_CLIENT_ENV_FILE", str(path))
    with pytest.raises(ValueError, match="exactly the three"):
        RabbitMQConfig.from_env()


def test_missing_generated_file_is_an_error(client_env, tmp_path):
    client_env.setenv("RABBITMQ_CLIENT_ENV_FILE", str(tmp_path / "missing"))
    with pytest.raises(FileNotFoundError):
        RabbitMQConfig.from_env()


@pytest.mark.parametrize("key,value", [("RABBITMQ_TOPOLOGY_VERSION", "2"), ("RABBITMQ_DLX", "old.dlx"),
                                       ("RABBITMQ_EXCHANGE_TYPE", "direct"), ("RABBITMQ_REQUEST_BINDING", "old.#")])
def test_incompatible_or_retired_settings_are_rejected(client_env, key, value):
    client_env.setenv(key, value)
    with pytest.raises(ValueError, match="Unsupported|retired"):
        RabbitMQConfig.from_env()


class PassiveChannel:
    """Deliberately offers no mutation or binding methods."""
    def __init__(self):
        self.checks = []
        self.consumed = False

    def exchange_declare(self, *, exchange, passive):
        assert passive is True
        self.checks.append(("exchange", exchange))

    def queue_declare(self, *, queue, passive):
        assert passive is True
        self.checks.append(("queue", queue))

    def basic_qos(self, prefetch_count):
        assert prefetch_count == 1

    def basic_consume(self, **kwargs):
        self.consumed = True

    def start_consuming(self):
        raise KeyboardInterrupt


class Connection:
    def __init__(self, channel):
        self.ch = channel
        self.is_open = True

    def channel(self):
        return self.ch

    def close(self):
        self.is_open = False


def test_setup_is_passive_and_closes_connection(client_env, monkeypatch, capsys):
    module = importlib.import_module("app.common.messaging.setup")
    channel = PassiveChannel()
    connection = Connection(channel)
    monkeypatch.setattr(module.pika, "BlockingConnection", lambda _: connection)
    module.setup()
    assert channel.checks == [("exchange", "from-platform"), ("queue", "from-platform.inbox")]
    assert not connection.is_open
    assert "exist" in capsys.readouterr().out


def test_setup_reports_missing_resources_without_creating_them(client_env, monkeypatch):
    module = importlib.import_module("app.common.messaging.setup")
    channel = PassiveChannel()
    def missing(**kwargs):
        raise pika.exceptions.ChannelClosedByBroker(404, "missing inbox")
    channel.queue_declare = missing
    connection = Connection(channel)
    monkeypatch.setattr(module.pika, "BlockingConnection", lambda _: connection)
    with pytest.raises(RuntimeError, match="404.*missing inbox"):
        module.setup()
    assert not connection.is_open


@pytest.mark.parametrize("error", [pika.exceptions.ChannelClosedByBroker(404, "not provisioned"),
                                    pika.exceptions.ConnectionClosedByBroker(320, "broker restarting")])
def test_worker_retries_missing_topology_or_transient_close_without_binding(client_env, monkeypatch, error):
    module = importlib.import_module("app.common.messaging.rabbitmq")
    bus = module.RabbitEventBus(RabbitMQConfig.from_env())
    bus.subscribe("platform.assessment.stage.requested", lambda message: None)
    missing_channel, ready_channel = PassiveChannel(), PassiveChannel()
    def missing(**kwargs):
        raise error
    missing_channel.queue_declare = missing
    connections = [Connection(missing_channel), Connection(ready_channel)]
    pending = iter(connections)
    monkeypatch.setattr(bus, "_connect", lambda: next(pending))
    waits = []
    monkeypatch.setattr(module.time, "sleep", waits.append)
    bus.start()
    assert waits == [5]
    assert ready_channel.consumed
    assert all(not connection.is_open for connection in connections)


@pytest.mark.parametrize("error", [pika.exceptions.ChannelClosedByBroker(403, "denied"),
                                    pika.exceptions.ChannelClosedByBroker(406, "inequivalent"),
                                    pika.exceptions.ConnectionClosedByBroker(530, "vhost denied"),
                                    pika.exceptions.ProbableAuthenticationError("bad password"),
                                    pika.exceptions.ProbableAccessDeniedError("vhost denied")])
def test_worker_does_not_retry_permission_or_configuration_errors(client_env, monkeypatch, error):
    module = importlib.import_module("app.common.messaging.rabbitmq")
    bus = module.RabbitEventBus(RabbitMQConfig.from_env())
    bus.subscribe("platform.assessment.stage.requested", lambda message: None)
    def refused():
        raise error
    monkeypatch.setattr(bus, "_connect", refused)
    monkeypatch.setattr(module.time, "sleep", lambda _: pytest.fail("permanent failure retried"))
    with pytest.raises(type(error)):
        bus.start()
